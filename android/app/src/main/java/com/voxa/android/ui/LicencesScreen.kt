/**
 * Settings, Open source licences: Voxa's NOTICE first, then every library, font and the Rust core's
 * crates this APK ships, each with its licence text a tap away. The data is
 * assets/licences.json.gzip (gzip; named so the build does not unpack it), generated by tools/licences/generate.py from the real dependency graph
 * (docs/guardrails.md#11-licences).
 */
object Licences {
    const val ASSET = "licences.json.gzip"

    class Library(val name: String, val version: String, val kind: String, val licence: String, val source: String, val note: String, val texts: List<Int>)

    class Notices(val app: String, val notice: String, val libraries: List<Library>, val texts: List<String>)

    fun load(ctx: Context): Notices {
        val json = GZIPInputStream(ctx.assets.open(ASSET)).bufferedReader(Charsets.UTF_8).use { it.readText() }
        return parse(json)
    }

    fun parse(json: String): Notices {
        val o = JSONObject(json)
        val libs = o.getJSONArray("libraries")
        val texts = o.getJSONArray("texts")
        return Notices(
            app = o.getString("app"),
            notice = o.getString("notice"),
            libraries = List(libs.length()) { i ->
                val l = libs.getJSONObject(i)
                val t = l.getJSONArray("texts")
                Library(
                    l.getString("name"), l.optString("version"), l.optString("kind"), l.getString("licence"),
                    l.optString("source"), l.optString("note"), List(t.length()) { t.getInt(it) },
                )
            },
            texts = List(texts.length()) { texts.getString(it) },
        )
    }

    /** The NOTICE wraps at 80 columns; on a phone a line that continues a sentence (it starts with a
     *  small letter or a digit) joins the one before, so the words reflow. Line and paragraph breaks
     *  between sentences stay. */
    fun reflow(text: String): String {
        val out = StringBuilder()
        for (line in text.trimEnd().lines()) {
            val continues = out.isNotEmpty() && !out.endsWith("\n\n") && line.firstOrNull()?.let { it.isLowerCase() || it.isDigit() } == true
            if (continues) {
                out.setLength(out.length - 1)
                out.append(' ')
            }
            out.append(line).append('\n')
        }
        return out.toString().trimEnd()
    }

    /** "MIT OR Apache-2.0" reads "MIT or Apache-2.0". */
    fun plain(spdx: String): String =
        spdx.replace(" OR ", " or ").replace(" AND ", " and ").replace(" WITH ", " with ").replace("/", " or ").replace("  ", " ")
}

@Composable
fun LicencesScreen(activity: MainActivity) {
    val c = vx
    val ctx = LocalContext.current
    val data by produceState<Result<Licences.Notices>?>(null) {
        value = withContext(Dispatchers.IO) { runCatching { Licences.load(ctx) } }
    }
    val open = remember { mutableStateListOf<Int>() }

    Column(Modifier.fillMaxSize()) {
        Row(Modifier.padding(horizontal = 24.dp).height(56.dp), verticalAlignment = Alignment.CenterVertically) {
            Box(
                Modifier.size(40.dp).clip(CircleShape).clickable(role = Role.Button) { activity.back() }
                    .semantics { contentDescription = "Back" },
                contentAlignment = Alignment.Center,
            ) {
                Icon(painterResource(R.drawable.ic_back), null, Modifier.size(24.dp), tint = c.text)
            }
            Spacer(Modifier.width(8.dp))
            Text("Open source licences", style = Type.L, color = c.text)
        }
        val notices = data?.getOrNull()
        when {
            data == null -> Unit
            notices == null -> Text(
                "The licences could not be read. They are also in THIRD_PARTY_NOTICES.txt with Voxa's source code.",
                Modifier.padding(24.dp), style = Type.M, color = c.text,
            )
            else -> LazyColumn(Modifier.fillMaxSize(), contentPadding = PaddingValues(start = 24.dp, end = 24.dp, bottom = 24.dp)) {
                item {
                    Text("Voxa", Modifier.padding(top = 8.dp, bottom = 12.dp), style = Type.SBold, color = c.text)
                    VCard(Modifier.padding(bottom = 24.dp), padding = PaddingValues(16.dp)) {
                        Text(Licences.reflow(notices.notice), style = Type.S, color = c.text)
                    }
                    Text("Built with ${notices.libraries.size} open source components", style = Type.SBold, color = c.text)
                    Text("Tap one to read its licence.", Modifier.padding(top = 4.dp, bottom = 12.dp), style = Type.XS, color = c.text56)
                }
                itemsIndexed(notices.libraries, key = { i, _ -> i }) { i, lib ->
                    val expanded = i in open
                    val first = i == 0
                    val last = i == notices.libraries.lastIndex
                    val shape = RoundedCornerShape(
                        topStart = if (first) 24.dp else 0.dp, topEnd = if (first) 24.dp else 0.dp,
                        bottomStart = if (last) 24.dp else 0.dp, bottomEnd = if (last) 24.dp else 0.dp,
                    )
                    Column(Modifier.fillMaxWidth().clip(shape).background(c.card)) {
                        if (!first) Box(Modifier.padding(horizontal = 16.dp).fillMaxWidth().height(1.dp).background(c.hair))
                        Row(
                            Modifier.fillMaxWidth()
                                .clickable(role = Role.Button) { if (expanded) open.remove(i) else open.add(i) }
                                .semantics { stateDescription = if (expanded) "Licence shown" else "Licence hidden" }
                                .padding(horizontal = 16.dp, vertical = 12.dp),
                            verticalAlignment = Alignment.CenterVertically,
                        ) {
                            Column(Modifier.weight(1f)) {
                                Text(if (lib.version.isEmpty()) lib.name else "${lib.name} ${lib.version}", style = Type.M, color = c.text)
                                Text(Licences.plain(lib.licence), style = Type.XS, color = c.text56)
                            }
                            Spacer(Modifier.width(12.dp))
                            Icon(painterResource(R.drawable.ic_chevron), null, Modifier.size(20.dp).rotate(if (expanded) 270f else 90f), tint = c.text56)
                        }
                        if (expanded) {
                            Column(Modifier.padding(start = 16.dp, end = 16.dp, bottom = 16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                                Text(if (lib.source.isEmpty()) lib.kind else "${lib.kind}, ${lib.source}", style = Type.XS, color = c.text56)
                                if (lib.note.isNotEmpty()) Text(lib.note, style = Type.S, color = c.text)
                                for (t in lib.texts) {
                                    Box(Modifier.fillMaxWidth().clip(RoundedCornerShape(12.dp)).background(c.base).padding(12.dp)) {
                                        Text(notices.texts[t].trimEnd(), style = Type.XS, color = c.text)
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
